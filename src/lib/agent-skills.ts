/**
 * One entry of `/.well-known/agent-skills/index.json` (Agent Skills
 * discovery v0.2.0), built from a SKILL.md's bytes. The frontmatter is
 * parsed as YAML (gray-matter), so quoted and folded values come out as the
 * text they stand for, and nothing in the body can pass for metadata.
 */
import { createHash } from "node:crypto";

import matter from "gray-matter";

export interface SkillEntry {
  description: string;
  digest: string;
  name: string;
  type: "skill-md";
  url: string;
}

export function skillEntry(name: string, bytes: Uint8Array): SkillEntry {
  const file = `${name}/SKILL.md`,
    text = new TextDecoder().decode(bytes);
  if (!matter.test(text)) {
    throw new Error(`${file}: no YAML frontmatter`);
  }
  // oxlint-disable-next-line eslint/one-var -- parsed only once frontmatter is known to be there
  const { data } = matter(text) as { data: Record<string, unknown> };
  if (data.name !== name) {
    throw new Error(`${file}: frontmatter name must be "${name}"`);
  }
  if (typeof data.description !== "string" || !data.description.trim()) {
    throw new Error(`${file}: frontmatter needs a description`);
  }
  return {
    description: data.description.trim(),
    digest: `sha256:${createHash("sha256").update(bytes).digest("hex")}`,
    name,
    type: "skill-md",
    url: `/.well-known/agent-skills/${name}/SKILL.md`,
  };
}

/** A concept as the skill generator needs it: where it lives and its name. */
export interface SkillConcept {
  label: string;
  retired: boolean;
  route: string;
}

export interface SkillArea {
  label: string;
  route: string;
  /** Live concepts under the area (topics and grouping headings), the area itself excluded. */
  topics: number;
}

export const AREAS_END = "<!-- areas:end -->",
  AREAS_START =
    "<!-- areas:start (generated by scripts/agent-skills-index.ts — do not edit) -->";

/**
 * The first level of the corpus: every live top-level area with the number of
 * live topics beneath it. An agent that has this list can go straight to
 * `list_concepts` with the right `area`, instead of guessing a route prefix.
 */
export function topLevelAreas(concepts: readonly SkillConcept[]): SkillArea[] {
  const counts = new Map<string, number>(),
    live = concepts.filter((concept) => !concept.retired && concept.route);
  for (const { route } of live) {
    const slash = route.indexOf("/");
    if (slash > 0) {
      const area = route.slice(0, slash);
      counts.set(area, (counts.get(area) ?? 0) + 1);
    }
  }
  return live
    .filter((concept) => !concept.route.includes("/"))
    .map((concept) => ({
      label: concept.label,
      route: concept.route,
      topics: counts.get(concept.route) ?? 0,
    }))
    .filter((area) => area.topics > 0)
    .toSorted((a, b) => a.label.localeCompare(b.label, "en"));
}

/** The generated block, markers included. One line per area: no table, so a formatter has nothing to realign. */
export function areasBlock(areas: readonly SkillArea[], site: string): string {
  const count = new Intl.NumberFormat("en-US"),
    lines = areas.map(
      (area) =>
        `- [${area.label}](${site}/${area.route}/) — \`${area.route}\` — ${count.format(area.topics)} topics`
    ),
    total = areas.reduce((sum, area) => sum + area.topics, 0);
  return [
    AREAS_START,
    "",
    `${count.format(total)} concepts (topics and the headings that group them) in ${areas.length} areas of law. The middle value is the value to pass as \`area\` to \`list_concepts\`.`,
    "",
    ...lines,
    "",
    AREAS_END,
  ].join("\n");
}

/** Replace the generated block of a SKILL.md. A file without the markers is an error, not a silent no-op. */
export function withAreas(text: string, block: string): string {
  const end = text.indexOf(AREAS_END),
    start = text.indexOf(AREAS_START);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("SKILL.md has no areas:start / areas:end markers");
  }
  return text.slice(0, start) + block + text.slice(end + AREAS_END.length);
}
