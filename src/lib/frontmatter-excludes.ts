/**
 * Corpus entries the build must skip: digests whose frontmatter fails the
 * schema, and data-collection entries (`run.json`) that are not valid JSON.
 * Recorded by scripts/check-digest-frontmatter.ts before every build and read
 * by src/content.config.ts, which leaves them out of the globs it declares.
 *
 * One malformed entry would otherwise abort the whole build, and only after
 * a multi-hour content sync. Excluding it drops one page (or one bundle's
 * provenance panel); the check prints every excluded file so the corpus can be
 * fixed upstream.
 *
 * The list lives at the repo root, is regenerated by every `pnpm run build`,
 * and is gitignored. A missing file means nothing is excluded.
 */
import { readFile } from "node:fs/promises";

import { escapePath } from "tinyglobby";

export const FRONTMATTER_EXCLUDES_FILE = ".frontmatter-excludes.json",
  /** Negated glob patterns (`!<path>`) for every excluded corpus entry, relative to CORPUS_DIR. */
  readFrontmatterExcludes = async (): Promise<string[]> => {
    let raw: string;
    try {
      raw = await readFile(FRONTMATTER_EXCLUDES_FILE, "utf8");
    } catch {
      return [];
    }
    const files: unknown = JSON.parse(raw);
    if (!Array.isArray(files)) {
      throw new TypeError(
        `${FRONTMATTER_EXCLUDES_FILE}: expected a JSON array of corpus paths`
      );
    }
    return files.map((file) => `!${escapePath(String(file))}`);
  };
